# Generates rtl/eog_defs.svh and spec/gen/bus_tables.md from the layouts below + buses.py.
# Run from FPGA/spec/gen:  python3 gendefs.py   (writes ../../rtl/eog_defs.svh and ./bus_tables.md)
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from buses import BUSES, layout
VER = int(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "VERSION")).read().strip())
S = 17
K_LEVEL = round(2**S * 16384 / 10000)
K_DIS = round(2**S * 16384 / 1500)
K_PIPE = round(2**S * 16384 / 500)
L = []
w = L.append
w(f"// eog_defs.svh -- GENERATED by FPGA/spec/gen/gendefs.py (spec VERSION {VER}). Do not edit by hand.")
w("// Include INSIDE each module body, after the port list:   `include \"eog_defs.svh\"")
w("")
w("// ---- sizes ----")
w(f"localparam integer EOG_SPEC_VERSION = {VER};")
w("localparam integer EOG_N_FAC   = 32;   // facility slots (5-bit flat id)")
w("localparam integer EOG_N_WELL  = 8;    // well slots per facility")
w("localparam integer EOG_N_FEAT  = 31;   // 12 channels + 19 memory features")
w("localparam integer EOG_N_CLS   = 4;    // [pipeline_leak, pump_degradation, pump_failure, facility_shut_in]")
w("localparam integer EOG_II_MAX  = 16;   // max cycles between accepted records per stage when downstream is ready")
w("localparam integer EOG_CD_N    = 16;   // countdown inflow ring depth")
w("")
w("// ---- numerics (numerics.md) ----")
w(f"localparam integer EOG_FEAT_SHIFT = {S};                 // S, fixed")
w(f"localparam logic [31:0] EOG_K_LEVEL = 32'd{K_LEVEL};       // round(2^17*16384/10000), channel 4")
w(f"localparam logic [31:0] EOG_K_DIS   = 32'd{K_DIS};      // round(2^17*16384/1500),  channel 5")
w(f"localparam logic [31:0] EOG_K_PIPE  = 32'd{K_PIPE};      // round(2^17*16384/500),   channel 6")
w("localparam integer EOG_ONE = 16384;                      // 1.0 in feature units")
w("localparam integer EOG_EMA_FAST = 3;                     // alpha = 1/8")
w("localparam integer EOG_EMA_SLOW = 6;                     // alpha = 1/64")
w("localparam integer EOG_CD_SCALE = 8;                     // minutes = (K_cd * dlevel) / (q << 8)")
w("localparam logic [15:0] EOG_CD_NONE = 16'hFFFF;          // not filling / > 45 days / unknown")
w("")
w("// ---- status codes ----")
for n, v in [("VALID", 0), ("HELD", 1), ("INVALID", 3), ("DROPPED", 4)]:
    w(f"localparam logic [2:0] EOG_ST_{n} = 3'd{v};")
w("")
w("// ---- reason bits (RESULT.reason, numerics.md section 6) ----")
R = [("FIELD_HELD", 0), ("GAP_HELD", 1), ("HIST_RESET", 2), ("OUT_OF_RANGE", 3), ("ILLEGAL_ENUM", 4), ("FEAT_SAT", 5),
     ("PUMP_INCONS", 6), ("WELL_INCONS", 7), ("DUPLICATE", 8), ("OUT_OF_ORDER", 9), ("UNKNOWN_FAC", 10),
     ("FIELD_ABSENT", 11), ("FRAMING", 12), ("NO_MODEL", 13), ("FIELD_LOST", 14)]
for n, v in R:
    w(f"localparam integer EOG_R_{n} = {v};")
w("")
w("// ---- rule bits (RESULT.rules) ----")
for n, v in [("PUMP_FAULT", 0), ("SHUT_IN", 1), ("LVL_SHUTDOWN", 2), ("LVL_WARNING", 3), ("NOT_FILLING", 4)]:
    w(f"localparam integer EOG_RULE_{n} = {v};")
w("")
TABLES = {
 "D": ("DATA record (48 B = 384 bits; byte k at bits [8k+7:8k])",
       [("FAC_ID", 0, 16), ("RSV0", 16, 16), ("TS", 32, 32), ("PRESENT", 64, 32), ("INFLOW", 96, 16), ("LEVEL", 112, 16),
        ("PUMP_FLOW", 128, 16), ("RECV_FLOW", 144, 16), ("DIS_PSI", 160, 16), ("PIPE_PSI", 176, 16), ("PUMP_ST", 192, 8),
        ("RSV1", 200, 8), ("WELL_ST", 208, 16), ("WELL_WATER", 224, 128), ("RSV2", 352, 32)]),
 "CFG": ("Facility CONFIG row (64 B = 512 bits)",
       [("FAC_ID", 0, 16), ("N_WELLS", 16, 8), ("FLAGS", 24, 8), ("M_INV_B", 32, 32), ("M_INV_Q", 64, 32), ("M_INV_W", 96, 32),
        ("M_NET", 128, 32), ("P0", 160, 16), ("SHUT_LVL", 176, 16), ("WARN_LVL", 192, 16), ("RSV", 208, 16), ("K_CD", 224, 32),
        ("LO", 256, 112), ("HI", 368, 112), ("WELL_LO", 480, 16), ("WELL_HI", 496, 16)]),
 "G": ("GLOBAL CONFIG (32 B = 256 bits)",
       [("S", 0, 8), ("HOLD_MAX", 8, 8), ("CD_LOG2", 16, 8), ("PERSIST_K", 24, 8), ("HB_PERIOD_MS", 32, 16),
        ("HB_TIMEOUT_MS", 48, 16), ("LOGIT_THR", 64, 64), ("GAP_THR", 128, 16), ("FLAGS", 144, 8), ("RSV0", 152, 8),
        ("SHUTIN_WATER_MAX", 160, 16), ("RSV1", 176, 80)]),
 "RES": ("RESULT record (32 B = 256 bits)",
       [("FAC_ID", 0, 16), ("STATUS", 16, 8), ("SINCE_RESET", 24, 8), ("TS", 32, 32), ("REASON", 64, 32), ("LOGITS", 96, 64),
        ("RULES", 160, 8), ("WVER", 168, 8), ("CD_P10", 176, 16), ("CD_P50", 192, 16), ("CD_P90", 208, 16), ("RESULT_NO", 224, 32)]),
 "AL": ("ALERT record (16 B = 128 bits)",
       [("FAC_ID", 0, 16), ("KIND", 16, 8), ("SOURCE", 24, 8), ("TS", 32, 32), ("RESULT_NO", 64, 32), ("RULES", 96, 8),
        ("CLASSES", 104, 8), ("CD_P10", 112, 16)]),
}
for pre, (title, fields) in TABLES.items():
    w(f"// ---- {title}: EOG_{pre}_<FIELD> = LSB, EOG_{pre}_<FIELD>_W = width ----")
    end = 0
    for n, o, wd in fields:
        assert o == end, (pre, n)
        end = o + wd
        w(f"localparam integer EOG_{pre}_{n} = {o}; localparam integer EOG_{pre}_{n}_W = {wd};")
    w(f"localparam integer EOG_{pre}_BITS = {end};")
    w("")
w("// DATA present bits: 0 inflow, 1 level, 2 pump status, 3 pump flow, 4 discharge, 5 receive flow, 6 pipeline psi,")
w("//                   8+i well status slot i, 16+i well water slot i")
w("// CONFIG LO/HI: 7 x s16, index j at [16j+15:16j] inside the field: 0 inflow, 1 level, 2 pump flow,")
w("//               3 receive flow, 4 discharge, 5 pipeline psi, 6 unused.  FLAGS bit 0 = enable")
w("localparam logic [7:0] EOG_AK_NS_RAISED = 8'd1;")
w("localparam logic [7:0] EOG_AK_ES_RAISED = 8'd2;")
w("localparam logic [7:0] EOG_AK_CLEARED   = 8'd3;")
w("localparam logic [7:0] EOG_AK_ACKED     = 8'd4;")
w("")
w("// ---- inter-stage buses (conventions.md section 4): EOG_B<bus>_<FIELD> = LSB, EOG_B<bus>_<FIELD>_W = width ----")
T = []
for b, desc, f in BUSES:
    lay, wd = layout(f)
    w(f"// bus {b}: {desc}")
    w(f"localparam integer EOG_B{b}_W = {wd};")
    for n, ww, o, d in lay:
        w(f"localparam integer EOG_B{b}_{n} = {o}; localparam integer EOG_B{b}_{n}_W = {ww};")
    w("")
    T.append(f"### Bus {b} ({desc}), {wd} bits\n\n| Field | LSB | Width | Meaning |\n| --- | --- | --- | --- |")
    for n, ww, o, d in lay:
        T.append(f"| `{n}` | {o} | {ww} | {d} |")
    T.append("")
here = os.path.dirname(os.path.abspath(__file__))
out_svh = os.path.join(here, "..", "..", "rtl", "eog_defs.svh")
open(out_svh, "w").write("\n".join(L) + "\n")
open(os.path.join(here, "bus_tables.md"), "w").write("\n".join(T))
print("wrote", os.path.normpath(out_svh), "K:", K_LEVEL, K_DIS, K_PIPE)
